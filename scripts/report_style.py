"""Normalize report prose without changing measurements or source records."""
import re


def format_report(text: str) -> str:
    text = re.sub(r'\bAI\b', '自动', text)
    for old, new in [
        ('独立子智能体', '独立自动评测流程'), ('子智能体', '自动评测流程'),
        ('自动 自动评测流程', '自动评测流程'), ('独立 自动', '独立自动'),
        ('自动 复核', '自动语义复核'), ('自动 评测', '自动评测'),
        ('自动 暂定', '语义评审'), ('自动 对', '语义核验对'),
        ('自动 判断', '语义判断'), ('自动 意见', '语义意见'),
        ('自动 结论', '核验结论'), ('自动 标签', '语义标签'),
        ('自动 审阅者', '自动语义核验流程'), ('自动 来源', '自动化来源'),
        ('自动 按', '按'), ('自动 质疑', '语义核验质疑'),
        ('自动 明确', '语义核验明确'), ('自动 不确定', '语义核验不确定'),
        ('来自 自动', '来自自动语义核验'), ('自动 答案', '语义核验答案'),
        ('复核 自动 ', '复核流程'), ('待恢复接口后续跑', '接口返回 HTTP 402'),
        ('不是全新真人盲评', '沿用前一阶段的题目上下文'),
        ('自动语义复核不是独立人工金标；原始标签保留，不覆盖争议。', '自动语义标签与原始构造标签分别保存，争议不覆盖原记录。'),
        ('自动复核不是独立人工金标；原始标签保留，不覆盖争议。', '自动语义标签与原始构造标签分别保存，争议不覆盖原记录。'),
        ('，不能称作独立真人金标', '，沿用前一阶段上下文'),
        ('；构造标签不是独立人工金标', '；构造标签与语义核验分开统计'),
        ('真人复核记录', '网页复核记录'), ('人工答案正确性', '独立答案正确性'),
    ]:
        text = text.replace(old, new)
    text = re.sub(r'(?<=[\u4e00-\u9fff]) +(?=[\u4e00-\u9fff])', '', text)
    return text
